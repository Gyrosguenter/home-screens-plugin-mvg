/** Wählt das passende Icon für den MVG-`transportType`. */
export function ModeIcon({ transportType, size }: { transportType: string; size: string }) {
  switch (transportType) {
    case 'UBAHN':
      return <UBahnIcon size={size} />;
    case 'SBAHN':
      return <SBahnIcon size={size} />;
    case 'TRAM':
      return <TramIcon size={size} />;
    case 'BUS':
    case 'REGIONAL_BUS':
      return <BusIcon size={size} />;
    default:
      return null;
  }
}
